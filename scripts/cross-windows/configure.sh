set -euo pipefail
source "$(dirname "$0")/env.sh"
cmake -S "$MP_WIN_WORK/build/windows/blender" -B "$MP_WIN_WORK/build/windows/native" -G Ninja \
  -DCMAKE_TOOLCHAIN_FILE="$MP_WIN_SCRIPTS/toolchain.cmake" \
  -DCMAKE_PROJECT_INCLUDE="$MP_WIN_SCRIPTS/project-hooks.cmake" \
  -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_PREFIX_PATH="$MP_WIN_QT;$MP_WIN_WORK/toolchains/windows/deps" \
  -DHDF5_DIR="$MP_WIN_WORK/toolchains/windows/deps/cmake" \
  -DHDF5_USE_STATIC_LIBRARIES=OFF \
  -DQT_HOST_PATH="$MP_WIN_WORK/toolchains/qt" \
  -DLIBDIR="$MP_WIN_WORK/build/windows/lib-windows_x64" \
  -DZLIB_LIBRARY_RELEASE="$MP_WIN_WORK/build/windows/lib-windows_x64/zlib/lib/libz_st.lib" \
  -DBTS_HOST_SOURCE_DIR="$MP_WIN_WORK/build/windows/mpainter-source/native/host" \
  -DCMAKE_INSTALL_PREFIX="$MP_WIN_WORK/build/windows/native/bin" \
  -DWITH_COMPILER_CCACHE=OFF -DWITH_BUILDINFO=OFF -DWITH_GTESTS=OFF \
  -DWITH_CYCLES_DEVICE_CUDA=ON -DWITH_CYCLES_CUDA_BINARIES=OFF \
  -DWITH_CYCLES_HIP_BINARIES=OFF -DWITH_CYCLES_ONEAPI_BINARIES=OFF \
  -DWITH_CYCLES_DEVICE_OPTIX=OFF -DWITH_CYCLES_DEVICE_HIP=OFF \
  -DWITH_CYCLES_DEVICE_ONEAPI=OFF -DWITH_VULKAN_BACKEND=OFF \
  -DWITH_BLENDER_THUMBNAILER=OFF -DWITH_WINDOWS_BUNDLE_CRT=OFF \
  -DNINJA_MAX_NUM_PARALLEL_LINK_JOBS=1 -DNINJA_MAX_NUM_PARALLEL_COMPILE_HEAVY_JOBS=3 \
  -DNINJA_MAX_NUM_PARALLEL_COMPILE_JOBS=6 \
  -DBUILD_TESTING=OFF "$@"
