"""Register of the BTS_* environment variables that mPainter's native code reads.

Imported by scripts/mp.py (`mp docs` writes docs/architecture/bts-variables.md,
`mp check` fails when it is stale). A variable counts when tracked code under
native/ reads it by name through getenv, qgetenv, qEnvironmentVariable* or
QProcessEnvironment::value. Names built at run time are not seen.
"""

import os
import re
import subprocess

SOURCE_SUFFIXES = (".cc", ".hh", ".inl", ".inc", ".h", ".cpp")
READ = re.compile(r'\b(getenv|qgetenv|qEnvironmentVariable(?:IsSet|IsEmpty|IntValue)?|environment\(\)\.value|'
                  r'systemEnvironment\(\)\.value)\(\s*"(BTS_[A-Z0-9_]+)"')
FOLDERS = ("native/host/", "native/harness/", "native/tests/", "native/")


def tracked(root):
    proc = subprocess.run(["git", "-C", str(root), "ls-files", "-z", "--", "native"], capture_output=True,
                          timeout=120, env=dict(os.environ, GIT_OPTIONAL_LOCKS="0"))
    if proc.returncode:
        raise RuntimeError("git ls-files failed; run inside a git worktree")
    return sorted(os.fsdecode(p) for p in proc.stdout.split(b"\0") if p)


def classify(root):
    """{name: {"files": {path: count}, "kinds": {call kinds}}}"""
    found = {}
    for rel in tracked(root):
        path = root / rel
        if not rel.endswith(SOURCE_SUFFIXES) or path.is_symlink() or not path.is_file():
            continue
        for kind, name in READ.findall(path.read_text(encoding="utf-8", errors="replace")):
            entry = found.setdefault(name, {"files": {}, "kinds": set()})
            entry["files"][rel] = entry["files"].get(rel, 0) + 1
            entry["kinds"].add(kind)
    return found


def area(path):
    for folder in FOLDERS:
        if path.startswith(folder):
            return folder.rstrip("/")
    return "other"


def render(found):
    harness_only = [n for n, e in found.items() if all(area(p) != "native/host" for p in e["files"])]
    lines = [
        "# BTS_* environment variables",
        "",
        "Generated by `python3 scripts/mp.py docs`. Do not edit by hand; `mp check` fails when it is stale.",
        "",
        "Every `BTS_*` variable that tracked code under `native/` reads by name. Most switch on a demo,",
        "a test or a diagnostic; they are the harness's interface and are not product settings.",
        "The restructure plan (phase 4) moves this register to `native/harness/` once the harness",
        "leaves the release build.",
        "",
        f"- Variables: {len(found)}",
        f"- Read only outside `native/host` (harness and tests): {len(harness_only)}",
        "",
        "| Variable | Read in | Files |",
        "|---|---|---|",
    ]
    for name in sorted(found):
        files = found[name]["files"]
        areas = ", ".join(sorted({area(p) for p in files}))
        shown = ", ".join(f"`{p.rsplit('/', 1)[-1]}`" for p in sorted(files)[:4])
        more = f" and {len(files) - 4} more" if len(files) > 4 else ""
        lines.append(f"| `{name}` | {areas} | {shown}{more} |")
    return "\n".join(lines) + "\n"
