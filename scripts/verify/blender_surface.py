#!/usr/bin/env python3
"""Generate docs/blender-surface.md: which Blender headers mPainter's own code includes.

  python3 scripts/verify/blender_surface.py --root . --write docs/blender-surface.md
  python3 scripts/verify/blender_surface.py --root . --check docs/blender-surface.md

Reads tracked C/C++ files under native/ (git ls-files) as text and classifies each
#include. An include is mPainter's own when it resolves to a tracked file: beside the
including file, in native/host/, native/ or the root. One that does not resolve is
Blender when it follows Blender's module naming (`BKE_context.hh`, `GPU_shader.hh`),
Qt when it starts with Q or qt, and otherwise "other external", listed by name so a
person can check it. Nothing is run. --check exits 1 when the file is stale.
"""

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

SOURCE_SUFFIXES = (".cc", ".hh", ".inl", ".c", ".cpp", ".h", ".hpp")
INCLUDE = re.compile(r'^[ \t]*#[ \t]*include[ \t]*([<"])([^">\n]+)[">]', re.M)
BLENDER_MODULE = re.compile(r"([A-Z][A-Z0-9]{1,7})_[A-Za-z0-9_]+\.(h|hh|hpp)\Z")
BLENDER_DIRS = ("intern/", "source/blender/", "extern/", "blender/")
QT = re.compile(r"(Q[A-Z]\w*|Qt\w*/\w+|q\w+\.h)\Z")
BOUNDARY = "native/host/blender/"


def tracked(root):
    proc = subprocess.run(["git", "-C", str(root), "ls-files", "-z", "--", "native"], capture_output=True,
                          timeout=120, env=dict(os.environ, GIT_OPTIONAL_LOCKS="0"))
    if proc.returncode:
        raise SystemExit("git ls-files failed; run inside a git worktree")
    return {os.fsdecode(p) for p in proc.stdout.split(b"\0") if p}


def domain_folders(files):
    return tuple(sorted({f.rsplit("/", 1)[0] for f in files if f.startswith("native/host/") and f.count("/") >= 3}))


def resolve(name, including, files, domains=()):
    folder = including.rsplit("/", 1)[0]
    # The same search order the build uses: the includer's folder, then the include
    # path every bts target gets (native/host, native/harness and the native/host
    # domain folders).
    for base in (folder, "native/host", "native/harness", *domains, "native", ""):
        candidate = os.path.normpath(f"{base}/{name}" if base else name).replace(os.sep, "/")
        if candidate in files:
            return candidate
    return None


def classify(root):
    files = tracked(root)
    domains = domain_folders(files)
    surface, others, includers = {}, {}, {}
    for rel in sorted(f for f in files if f.endswith(SOURCE_SUFFIXES)):
        path = root / rel
        if path.is_symlink() or not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for _, name in INCLUDE.findall(text):
            if resolve(name, rel, files, domains):
                continue
            module = BLENDER_MODULE.fullmatch(name.rsplit("/", 1)[-1])
            if module or name.startswith(BLENDER_DIRS):
                key = module.group(1) if module else name.split("/")[0]
                surface.setdefault(key, {}).setdefault(name, set()).add(rel)
                includers.setdefault(rel, set()).add(name)
            elif not QT.match(name) and "." in name.rsplit("/", 1)[-1]:
                others.setdefault(name, set()).add(rel)
    return surface, others, includers


def render(surface, others, includers):
    outside = sorted(f for f in includers if not f.startswith(BOUNDARY))
    lines = [
        "# Blender surface",
        "",
        "Generated by `scripts/verify/blender_surface.py`. Do not edit by hand; run it with `--write`.",
        "",
        "It lists every Blender header that tracked code under `native/` includes. A header counts",
        "as Blender when it does not resolve to a tracked file and follows Blender's `MODULE_name.h`",
        "naming. The restructure plan moves all of these includes behind `native/host/blender/` (phase 5).",
        "",
        f"- Blender headers: {sum(len(h) for h in surface.values())}, in {len(surface)} modules",
        f"- Files that include them: {len(includers)}, of which {len(outside)} are outside `{BOUNDARY}`",
        "",
        "| Module | Header | Files that include it |",
        "|---|---|---|",
    ]
    for module in sorted(surface):
        for header in sorted(surface[module]):
            lines.append(f"| {module} | `{header}` | {len(surface[module][header])} |")
    lines += ["", "## Unresolved includes that are neither Blender nor Qt", "",
              "Check these by hand: system, OpenUSD, MaterialX and other libraries land here.", ""]
    lines += [f"- `{name}` ({len(others[name])} files)" for name in sorted(others)] or ["- none"]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", required=True, type=Path)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", type=Path)
    mode.add_argument("--check", type=Path)
    args = parser.parse_args(argv)
    root = args.root.resolve()
    content = render(*classify(root))
    target = (root / (args.write or args.check)).resolve()
    if root not in target.parents:
        print("the output must be inside the root", file=sys.stderr)
        return 2
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current != content:
            print(f"{args.check} is {'missing' if current is None else 'stale'}; "
                  f"run blender_surface.py --write {args.check}")
            return 1
        print(f"{args.check} is current")
        return 0
    if target.is_symlink():
        print("refusing to write through a symlink", file=sys.stderr)
        return 2
    target.write_text(content, encoding="utf-8")
    print(f"wrote {args.write}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
